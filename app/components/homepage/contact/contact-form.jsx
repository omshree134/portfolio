"use client";
// @flow strict
import { isValidEmail } from "@/utils/check-email";
import { personalData } from "@/utils/data/personal-data";
import axios from "axios";
import { useState } from "react";
import { TbMailForward } from "react-icons/tb";
import { toast } from "react-toastify";

function ContactForm() {
  const [error, setError] = useState({ email: false, required: false });
  const [isLoading, setIsLoading] = useState(false);
  const [userInput, setUserInput] = useState({
    name: "",
    email: "",
    message: "",
  });

  const checkRequired = () => {
    if (userInput.email && userInput.message && userInput.name) {
      setError({ ...error, required: false });
    }
  };

  const handleSendMail = async (e) => {
    e.preventDefault();

    if (!userInput.email || !userInput.message || !userInput.name) {
      setError({ ...error, required: true });
      return;
    } else if (error.email) {
      return;
    } else {
      setError({ ...error, required: false });
    };

    try {
      setIsLoading(true);
      const res = await axios.post(
        `https://formsubmit.co/ajax/${personalData.email}`,
        userInput
      );

      toast.success("Message sent successfully!");
      setUserInput({
        name: "",
        email: "",
        message: "",
      });
    } catch (error) {
      toast.error(error?.response?.data?.message);
    } finally {
      setIsLoading(false);
    };
  };

  return (
    <div>
      <div className="max-w-3xl text-paper border border-line bg-panel p-4 lg:p-6">
        <p className="text-sm text-muted">{"If you have any questions or concerns, please don't hesitate to contact me. I am open to any work opportunities that align with my skills and interests."}</p>
        <div className="mt-6 flex flex-col gap-4">
          <div className="flex flex-col gap-2">
            <label className="font-[family-name:var(--font-mono)] text-[11px] tracking-[0.2em] text-muted">YOUR NAME </label>
            <input
              className="bg-ink w-full border border-line focus:border-cc ring-0 outline-0 transition-colors duration-200 px-3 py-2 text-paper"
              type="text"
              maxLength="100"
              required={true}
              onChange={(e) => setUserInput({ ...userInput, name: e.target.value })}
              onBlur={checkRequired}
              value={userInput.name}
            />
          </div>

          <div className="flex flex-col gap-2">
            <label className="font-[family-name:var(--font-mono)] text-[11px] tracking-[0.2em] text-muted">YOUR EMAIL </label>
            <input
              className="bg-ink w-full border border-line focus:border-cc ring-0 outline-0 transition-colors duration-200 px-3 py-2 text-paper"
              type="email"
              maxLength="100"
              required={true}
              value={userInput.email}
              onChange={(e) => setUserInput({ ...userInput, email: e.target.value })}
              onBlur={() => {
                checkRequired();
                setError({ ...error, email: !isValidEmail(userInput.email) });
              }}
            />
            {error.email && <p className="text-sm text-red-400">Please provide a valid email!</p>}
          </div>

          <div className="flex flex-col gap-2">
            <label className="font-[family-name:var(--font-mono)] text-[11px] tracking-[0.2em] text-muted">YOUR MESSAGE </label>
            <textarea
              className="bg-ink w-full border border-line focus:border-cc ring-0 outline-0 transition-colors duration-200 px-3 py-2 text-paper"
              maxLength="500"
              name="message"
              required={true}
              onChange={(e) => setUserInput({ ...userInput, message: e.target.value })}
              onBlur={checkRequired}
              rows="4"
              value={userInput.message}
            />
          </div>
          <div className="flex flex-col items-center gap-3">
            {error.required && <p className="text-sm text-red-400">
              All fields are required!
            </p>}
            <button
              className="flex items-center gap-2 bg-cc text-ink px-8 py-3 text-center text-xs font-bold uppercase tracking-[0.2em] transition-colors duration-200 hover:bg-paper disabled:opacity-60"
              role="button"
              onClick={handleSendMail}
              disabled={isLoading}
            >
              {
                isLoading ?
                <span>Sending Message...</span>:
                <span className="flex items-center gap-1">
                  Send Message
                  <TbMailForward size={20} />
                </span>
              }
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};

export default ContactForm;
